# Run from the repo root (dev-only; tests/ is not shipped):
#   python -I tests/make_object_models.py [--cmangos ClassicDB_*.sql.gz]
# (default: the newest ClassicDB_*.sql.gz in C:\Users\Dawson\Desktop\claude stuff\CMaNGOS, kept there for this)
# Writes Tracker/ObjectModels.lua (R106-99): game object id -> model file id, for the model panel (Tracker/NpcPanel.lua).
# The game has no lookup from an object to its model. An object's display id comes from the server, so no client table
# has it for quest objects (the client's GameObjects table holds only ~1,500 placed signposts and doors). Sources:
#   1. the game's object cache (Forever's Cache/WDB/enUS/gameobjectcache.wdb: every object the server described to
#      this client, with its display id), turned into model files by this build's GameObjectDisplayInfo table read
#      from the local game files (tests/casc_read.py); this source wins, being this build's own data;
#   2. the CMaNGOS Classic database (github.com/cmangos/classic-db, Full_DB/ClassicDB_1_12_1_*.sql.gz, GPL-3.0; its
#      gameobject_template: entry, type, displayId, name), display ids turned into model files the same way;
#   3. tests/extra_object_models.txt: pairs for objects in neither (user's call); the two above win over it.
import glob, gzip, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import casc_read

args = dict(zip(sys.argv[1::2], sys.argv[2::2]))
CMANGOS_DIR = r"C:\Users\Dawson\Desktop\claude stuff\CMaNGOS"
cmangos = args.get("--cmangos") or (sorted(glob.glob(os.path.join(CMANGOS_DIR, "ClassicDB_*.sql.gz"))) or [None])[-1]
ROW = re.compile(r"\((\d+),(\d+),(\d+),'((?:[^'\\]|\\.)*)'")


def cmangos_objects(path):
    """{entry: displayId} from the dump's gameobject_template INSERTs."""
    out = {}
    with gzip.open(path, "rt", encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith("INSERT INTO `gameobject_template`"):
                for entry, _, display, _ in ROW.findall(line):
                    out[int(entry)] = int(display)
    return out


models = {}
EXTRA = os.path.join(os.path.dirname(os.path.abspath(__file__)), "extra_object_models.txt")
extra = 0
if os.path.exists(EXTRA):
    with open(EXTRA, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"^(\d+)\t(\d+)", line)
            if m:
                models[int(m.group(1))] = int(m.group(2))
                extra += 1
# With no --cmangos file, the pairs already in Tracker/ObjectModels.lua are kept as the base (3.2, user: new Forever
# objects such as the Cattail had no model; the game cache now has many more objects than at the first run).
kept = 0
if not cmangos:
    out_path = os.path.join("Tracker", "ObjectModels.lua")
    if os.path.exists(out_path):
        with open(out_path, encoding="utf-8") as f:
            for k, v in re.findall(r"t\[(\d+)\] = (\d+)", f.read()):
                models[int(k)] = int(v)
                kept += 1

casc = casc_read.Casc("wowf")
display = casc.table("GameObjectDisplayInfo")
files = {rid: display.value(rid, 1) for rid in display.rows}
from_cmangos = 0
if cmangos:
    for oid, display_id in cmangos_objects(cmangos).items():
        f = files.get(display_id)
        if f:
            models[oid] = f
            from_cmangos += 1
cached = 0
for oid, (_, display_id, _) in casc_read.object_cache().items():
    f = files.get(display_id)
    if f:
        models[oid] = f
        cached += 1

with open(os.path.join("Tracker", "ObjectModels.lua"), "w", encoding="utf-8", newline="\n") as f:
    f.write("-- R106-99: game object id -> model file id, for the model panel (Tracker/NpcPanel.lua). Generated by\n")
    if cmangos:
        f.write("-- tests/make_object_models.py; do not edit by hand. %d objects (game cache %d, CMaNGOS %d, extra list %d;"
                " build %s).\n" % (len(models), cached, from_cmangos, extra, casc.build_name))
    else:
        f.write("-- tests/make_object_models.py; do not edit by hand. %d objects (game cache %d, the rest kept from"
                " the last run; build %s).\n" % (len(models), cached, casc.build_name))
    f.write("local _, root = ...; local ns = root.tracker\n")
    f.write("if ns.disabled then return end\n")
    f.write("local t = ns.objectModels or {}\n")
    f.write("ns.objectModels = t\n")
    ids = sorted(models)
    for i in range(0, len(ids), 6):
        f.write(" ".join("t[%d] = %d" % (k, models[k]) for k in ids[i:i + 6]) + "\n")
print("wrote Tracker/ObjectModels.lua: %d objects (extra list %d, kept %d, CMaNGOS %d, game cache %d)"
      % (len(models), extra, kept, from_cmangos, cached))

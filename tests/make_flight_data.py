# Dev-only (tests/ is not shipped). Writes Tracker/FlightData.lua (R311-8): the flown length of every flight path, from
# this game build's own TaxiPath and TaxiPathNode tables. Run from the repo root:
#   python -I tests/make_flight_data.py [folder with TaxiPath.csv and TaxiPathNode.csv]
# The CSV files come from wow.export (github.com/Kruithne/wow.export): Open Local Installation > World of Warcraft
# Forever > Data tab > "Export all rows" on > Export as CSV, for TaxiPath and TaxiPathNode (default folder
# %USERPROFILE%\wow.export). Run it again when the game adds flight paths.
# A path is a list of points (NodeIndex order). Its length is the sum of the straight 3D steps between them, so the
# curves count; a step after a teleport point (flag 1) or onto another continent is not flown and not counted. Points
# with a wait (Delay, seconds) add that wait to the path.
import csv, math, os, sys

src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.expanduser("~"), "wow.export")
out = os.path.join("Tracker", "FlightData.lua")


def rows(name):
    with open(os.path.join(src, name + ".csv"), encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f, delimiter=";"))


paths = {int(r["ID"]): (int(r["FromTaxiNode"]), int(r["ToTaxiNode"])) for r in rows("TaxiPath")}
points = {}
for r in rows("TaxiPathNode"):
    x, y, z = (float(v) for v in r["Loc"].split(","))
    points.setdefault(int(r["PathID"]), []).append(
        (int(r["NodeIndex"]), x, y, z, int(r["ContinentID"]), int(r["Flags"]), int(r["Delay"] or 0)))

lengths, waits = {}, {}
for pid, (a, b) in sorted(paths.items()):
    pts = sorted(points.get(pid, []))
    if len(pts) < 2:
        continue
    total, wait = 0.0, 0
    for prev, cur in zip(pts, pts[1:]):
        if prev[5] & 1 or prev[4] != cur[4]:
            continue
        total += math.sqrt((cur[1] - prev[1]) ** 2 + (cur[2] - prev[2]) ** 2 + (cur[3] - prev[3]) ** 2)
    for p in pts[1:-1]:
        wait += p[6]
    key = a * 10000 + b
    if a > 0 and b > 0 and total > 0 and key not in lengths:
        lengths[key] = round(total)
        if wait:
            waits[key] = wait

with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- Generated by tests/make_flight_data.py from this game build's TaxiPath and TaxiPathNode tables (R311-8).\n")
    f.write("-- Flown length in yards of each flight path, keyed fromNodeID * 10000 + toNodeID; waits: seconds stopped on the way.\n")
    f.write("local ADDON, root = ...; local ns = root.tracker\n")
    f.write("ns.flightPathYards = {\n")
    for k in sorted(lengths):
        f.write("\t[%d] = %d,\n" % (k, lengths[k]))
    f.write("}\n")
    f.write("ns.flightPathWaits = {\n")
    for k in sorted(waits):
        f.write("\t[%d] = %d,\n" % (k, waits[k]))
    f.write("}\n")
print("%s: %d paths, %d with waits" % (out, len(lengths), len(waits)))
